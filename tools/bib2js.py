#!/usr/bin/env python3
"""
tools/bib2js.py — turn a BibTeX file (e.g. a NASA ADS export) into entries
for data/publications.js.

    python3 tools/bib2js.py my-papers.bib > publications-draft.js

Then copy the objects you want into the Site.data.publications array and
add the things BibTeX doesn't know about: `figure`, `tags`, `featured`,
`links.code`, etc.

Getting a .bib from ADS: run your author query at https://ui.adsabs.harvard.edu,
select all -> Export -> BibTeX (tick "include abstracts" under the export
settings if you want them).

No dependencies; the parser handles normal ADS output (nested braces,
"quoted" values, bare numbers). It is not a full BibTeX implementation.
"""
import json
import re
import sys

ENTRY_TYPES = {
    "article": "article",
    "inproceedings": "proceedings",
    "proceedings": "proceedings",
    "phdthesis": "thesis",
    "mastersthesis": "thesis",
    "software": "software",
    "misc": "preprint",
}

# Common ADS journal macros -> readable names. Add more as needed.
JOURNALS = {
    r"\apj": "ApJ", r"\apjl": "ApJL", r"\apjs": "ApJS", r"\aj": "AJ",
    r"\mnras": "MNRAS", r"\aap": "A&A", r"\pasp": "PASP", r"\nat": "Nature",
    r"\araa": "ARA&A", r"\prd": "PhRvD", r"\jcap": "JCAP",
}


def parse_bibtex(text):
    """Yield (entry_type, key, {field: value}) for each @entry{...}."""
    i = 0
    while True:
        m = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", re.S).search(text, i)
        if not m:
            return
        etype, key, i = m.group(1).lower(), m.group(2), m.end()
        fields = {}
        while True:
            fm = re.compile(r"\s*(\w+)\s*=\s*", re.S).match(text, i)
            if not fm:
                break
            name, i = fm.group(1).lower(), fm.end()
            value, i = read_value(text, i)
            fields[name] = value
            cm = re.compile(r"\s*,?", re.S).match(text, i)
            i = cm.end()
        close = text.find("}", i)
        i = close + 1 if close != -1 else len(text)
        yield etype, key, fields


def read_value(text, i):
    """Read a {braced}, "quoted" or bare value starting at text[i]."""
    if text[i] == "{":
        depth, j = 0, i
        while j < len(text):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            if depth == 0:
                return text[i + 1:j], j + 1
            j += 1
    if text[i] == '"':
        j = i + 1
        depth = 0
        while j < len(text) and not (text[j] == '"' and depth == 0):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        return text[i + 1:j], j + 1
    m = re.compile(r"[^,}\s]+").match(text, i)
    return m.group(0), m.end()


def clean(s):
    """Strip BibTeX braces and collapse whitespace (keeps $math$)."""
    s = re.sub(r"(?<!\\)[{}]", "", s or "")
    return re.sub(r"\s+", " ", s).strip()


def authors(field):
    """'{Astronomer}, A. and {Collaborator}, B.' -> ['A. Astronomer', 'B. Collaborator']."""
    out = []
    for name in re.split(r"\s+and\s+", field or ""):
        name = clean(name)
        if name.lower() == "others":
            out.append("et al.")
        elif "," in name:
            last, first = [p.strip() for p in name.split(",", 1)]
            out.append(f"{first} {last}".strip())
        elif name:
            out.append(name)
    return out


def convert(etype, key, f):
    pub = {
        "id": re.sub(r"[^A-Za-z0-9_-]+", "-", key).strip("-").lower(),
        "title": clean(f.get("title")),
        "authors": authors(f.get("author")),
        "year": int(re.sub(r"\D", "", f.get("year", "0")) or 0),
        "journal": JOURNALS.get(f.get("journal", "").strip(), clean(f.get("journal") or f.get("booktitle") or f.get("school"))),
        "volume": clean(f.get("volume")),
        "pages": clean(f.get("pages") or f.get("eid")),
        "type": ENTRY_TYPES.get(etype, "article"),
        "abstract": clean(f.get("abstract")),
        "links": {},
        "tags": [],
    }
    if f.get("adsurl"):
        pub["links"]["ads"] = clean(f["adsurl"])
    if f.get("eprint"):
        pub["links"]["arxiv"] = clean(f["eprint"])
    if f.get("doi"):
        pub["links"]["doi"] = clean(f["doi"])
    # Drop empty fields to keep the output tidy.
    return {k: v for k, v in pub.items() if v not in ("", None, {}, [])} | {"tags": []}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as fh:
        text = fh.read()
    pubs = [convert(*e) for e in parse_bibtex(text)]
    print("// Generated by tools/bib2js.py — paste into Site.data.publications in data/publications.js")
    print(json.dumps(pubs, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
